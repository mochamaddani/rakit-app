// Compiles block stylesheets and snippets (and the editor's *.bundle.ts entries) into committed TS
// modules, so renderPage can run in the browser without a build tool (docs/DECISIONS.md D-013).
// Usage: pnpm assets (write stale outputs) | pnpm assets:check (exit 1 when any output is stale)
import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build, transform, type BuildOptions } from 'esbuild';

export interface AssetOutput {
  sourcePath: string;
  outputPath: string;
  contents: string;
}

const CSS_TARGETS = ['chrome100', 'safari15', 'firefox100'];

async function compile(path: string, source: string): Promise<{ min: string; src: string }> {
  if (path.endsWith('.css')) {
    const min = await transform(source, { loader: 'css', minify: true, target: CSS_TARGETS });
    return { min: min.code.trim(), src: source };
  }
  const options = {
    loader: 'js',
    format: 'iife',
    target: 'es2017',
    legalComments: 'none',
  } as const;
  const [min, src] = await Promise.all([
    transform(source, { ...options, minify: true }),
    transform(source, options),
  ]);
  return { min: min.code.trim(), src: src.code.trim() };
}

/** `*.bundle.ts` entries (the editor canvas runtime) are bundled with their imports into one IIFE. */
async function compileBundle(entry: string): Promise<{ min: string; src: string }> {
  const options: BuildOptions & { write: false } = {
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    legalComments: 'none',
  };
  const [min, src] = await Promise.all([build({ ...options, minify: true }), build(options)]);
  return { min: min.outputFiles[0]!.text.trim(), src: src.outputFiles[0]!.text.trim() };
}

function moduleText(sourceName: string, asset: { min: string; src: string }): string {
  return [
    `// Generated by scripts/build-assets.ts from ${sourceName}. Do not edit; run \`pnpm assets\`.`,
    `import type { GeneratedAsset } from '@/lib/renderer/generated-asset';`,
    '',
    'export const asset: GeneratedAsset = {',
    `  min: ${JSON.stringify(asset.min)},`,
    `  src: ${JSON.stringify(asset.src)},`,
    '};',
    '',
  ].join('\n');
}

export async function buildAssets(rootDir: string): Promise<AssetOutput[]> {
  const sources = [
    ...globSync('lib/**/*.css', { cwd: rootDir }),
    ...globSync('lib/**/snippet.js', { cwd: rootDir }),
    ...globSync('lib/**/*.bundle.ts', { cwd: rootDir }),
  ].sort();
  return Promise.all(
    sources.map(async (relativePath) => {
      const sourcePath = join(rootDir, relativePath);
      const name = basename(relativePath);
      const isBundle = name.endsWith('.bundle.ts');
      const asset = isBundle
        ? await compileBundle(sourcePath)
        : await compile(relativePath, readFileSync(sourcePath, 'utf8').replace(/\r\n/g, '\n'));
      return {
        sourcePath,
        outputPath: join(
          dirname(sourcePath),
          name.replace(isBundle ? /\.bundle\.ts$/ : /\.(css|js)$/, '.generated.ts'),
        ),
        contents: moduleText(name, asset),
      };
    }),
  );
}

function isStale(output: AssetOutput): boolean {
  try {
    return readFileSync(output.outputPath, 'utf8') !== output.contents;
  } catch {
    return true;
  }
}

export async function main(argv: string[]): Promise<number> {
  const root = process.cwd();
  const stale = (await buildAssets(root)).filter(isStale);
  if (argv.includes('--check')) {
    for (const output of stale) console.error(`stale: ${relative(root, output.outputPath)}`);
    return stale.length > 0 ? 1 : 0;
  }
  for (const output of stale) {
    writeFileSync(output.outputPath, output.contents);
    console.log(`wrote ${relative(root, output.outputPath)}`);
  }
  if (stale.length === 0) console.log('assets are up to date');
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
